export function localReply(question: string, cabinet: string | null) {
  const q = question.toLowerCase().replaceAll("ё", "е");
  const bits: string[] = [];
  if (/привет|здравств|добрый/.test(q)) {
    bits.push("Здравствуйте. Мы команда AvitoOps: копирайтер, дизайнер и менеджер по общению. Можем рассказать про сайт и кабинет.");
  }
  if (/тариф|цен|стоим|сколько|подписк|старт|рост|бизнес|сеть/.test(q)) {
    bits.push(`${tariffLine}. Подробности на странице тарифов. Рекламный бюджет платится отдельно, с депозита.`);
  }
  if (/регистр|начать|подключ|аккаунт|войти|логин/.test(q)) {
    bits.push(
      "Зарегистрироваться можно сразу. Первый день — тариф Сеть бесплатно. Тариф в форме — тот, что начнётся после подтверждения оплаты. Войти в уже созданный аккаунт можно со страницы входа.",
    );
  }
  if (/парол|смс|код/.test(q)) {
    bits.push("Пароль Авито и коды из SMS мы не просим и не храним. Пароль на сайте задаёте сами при регистрации.");
  }
  if (/вместо меня|заполнить агент|агент заполн/.test(q)) {
    bits.push(
      "На тарифах Рост, Бизнес и Сеть в анкете есть кнопка «Заполнить агенту вместо меня». Куратор задаёт вопросы и вписывает ответы в поля. Галочку согласия ставите сами. На Старте анкету заполняют вручную.",
    );
  } else if (/ручн|объявлен|онбординг|форм|ввести|заполн|анкет/.test(q)) {
    bits.push(
      "Объявление и депозит вводят вручную. Анкету на Росте, Бизнесе и Сети может заполнить агент по вопросам. На Старте её заполняют сами. Из чата объявления не публикуются.",
    );
  }
  if (/кто вы|кто ты|вы кто|ты кто|представьтесь|представься/.test(q)) {
    bits.push(
      "Мы команда AvitoOps. Копирайтер пишет тексты объявлений, дизайнер собирает карточку и фото, менеджер по общению отвечает покупателям. Публикации, правки и рутину ведём вместе.",
    );
  }
  if (/лид|чат|ответ/.test(q) && !/кто вы|кто ты|вы кто|ты кто|представь/.test(q)) {
    bits.push(
      "В чате Авито менеджер по общению пишет так, как вы указали в анкете, в поле «Как отвечать покупателям». Если покупатель просит скидку, хочет забрать сегодня или жалуется — и в других случаях из поля «Когда сразу написать вам» — сообщение передают вам. Посмотреть их можно в разделе «Лиды».",
    );
  }
  if (/пауз|останов/.test(q)) {
    bits.push("Пауза в настройках кабинета останавливает публикации, правки и ответы. Вернуть работу можно, пока оплаченный период не закончился.");
  }
  if (/депозит|реклам/.test(q)) {
    bits.push(
      yookassaConfigured()
        ? "Реклама Авито не входит в подписку. Сумму кладёте на депозит в биллинге, оплата открывается в ЮKassa."
        : "Реклама Авито не входит в подписку. Сумму кладёте на депозит заявкой в биллинге, оператор её подтверждает.",
    );
  }
  if (/оплат|счет|счёт|юкасс|юkassa/.test(q)) {
    bits.push(
      yookassaConfigured()
        ? "Тариф и депозит оплачиваются в ЮKassa из раздела «Биллинг». Карту на сайте не вводим. После оплаты тариф или депозит включается сам."
        : "Тариф и депозит пока подтверждает оператор по заявке из кабинета.",
    );
  }
  if (/прокси|канал/.test(q)) {
    bits.push("Подключение к Авито делаем мы. Отдельные настройки вам не нужны.");
  }
  if (/отчет|отчёт|гарант|топ|продаж/.test(q)) {
    bits.push("Топ в поиске, обход правил и мгновенные продажи не обещаем. Еженедельный отчёт в работу пока не входит.");
  }
  if (/куки|cookie/.test(q)) {
    bits.push("Cookie нужны, чтобы после входа вы оставались в кабинете. Рекламных cookie нет. Согласие показывается внизу страницы.");
  }
  if (/оферт|договор|юрист/.test(q)) {
    bits.push("Оферта лежит на странице оферты. Контакты и реквизиты — на странице контактов.");
  }
  if (cabinet && /мой|мои|статус|сколько у|кабинет/.test(q)) bits.push(cabinet);
  if (bits.length === 0) {
    bits.push(
      "Могу ответить про тарифы, регистрацию, оплату, депозит и что заполняется в кабинете вручную. Напишите вопрос своими словами. Чтобы мы начали вести Авито, нужна регистрация.",
    );
  }
  return bits.join(" ");
}

async function grokReply(message: string, history: CuratorTurn[], cabinet: string | null) {
  const prior = history
    .slice(-6)
    .map((turn) => `${turn.role === "user" ? "Клиент" : "Куратор"}: ${turn.content}`)
    .join("\n");
  return askGrok(curatorSystemPrompt(cabinet), prior ? `${prior}\nКлиент: ${message}` : message);
}

export async function replyAsCurator(
  message: string,
  history: CuratorTurn[],
  cabinet: string | null,
  useModel: boolean,
) {
  if (useModel && process.env.XAI_API_KEY) {
    try {
      const text = await grokReply(message, history, cabinet);
      if (text) return text;
    } catch {
      return localReply(message, cabinet);
    }
  }
  return localReply(message, cabinet);
}

export function cabinetBrief(input: {
  plan: string | null;
  subscriptionStatus: string | null;
  access: string;
  listingCount: number;
  publishStarted: number;
  publishQuota: number;
  publishQueued: number;
  depositRub: number;
  hasProfile: boolean;
}) {
  const daily =
    input.plan && isPlan(input.plan)
      ? `За сутки на тарифе: ${DAILY_QUOTA[input.plan].publish} объявлений, ${DAILY_QUOTA[input.plan].update} правок, продвижение до ${DAILY_QUOTA[input.plan].promo} объявлений. Ответы покупателям по правилам клиента.`
      : "Тариф ещё не выбран.";
  return [
    `Тариф: ${planTitle(input.plan)}.`,
    daily,
    `Выкладка сегодня: ${input.publishStarted} из ${input.publishQuota}, в очереди ${input.publishQueued}.`,
    `Подписка: ${input.subscriptionStatus ? subscriptionStatusLabel(input.subscriptionStatus) : "нет оплаты"}.`,
    `Доступ: ${accessLabel(input.access)}.`,
    `Карточек в кабинете: ${input.listingCount}. Число карточек тарифом не ограничено.`,
    `Депозит: ${formatRub(input.depositRub)}.`,
    input.hasProfile ? "Профиль онбординга заполнен." : "Профиль онбординга ещё пустой, его вводят вручную.",
  ].join(" ");
}
