export type CuratorTurn = { role: "user" | "assistant"; content: string };

const tariffLine = Object.values(PLANS)
  .map((plan) => `${plan.title}: ${formatRub(plan.priceRub)} в месяц, ${plan.points.slice(0, 3).join(", ")}`)
  .join(". ");

export function guestPriceLine() {
  return `Старт — ${formatRub(PLANS.start.priceRub)} в месяц, три объявления в сутки. OPS на связи круглые сутки. Это дешевле частного авитолога и агентства.`;
}

export function speak(text: string) {
  return redact(text)
    .replace(/утром/gi, "в эти сутки")
    .replace(/к утру/gi, "когда сутки сменятся")
    .replace(/(^|[^а-яё])бот(?:а|ы|ов|ом|у|е|ами)?(?![а-яё])/gi, "$1ассистент")
    .replace(/прокси/gi, "подключение")
    .replace(/excel/gi, "таблица")
    .replace(/юkassa|юкасса|yookassa/gi, "оплата в биллинге");
}

export function clientSpeechOk(text: string) {
  const word = text.toLowerCase().replaceAll("ё", "е");
  return !/утром|к утру/.test(word) && !/(^|[^а-яе])бот(?:а|ы|ов|ом|у|е|ами)?(?![а-яе])/.test(word);
}

