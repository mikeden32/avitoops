export function localReply(question: string, cabinet: string | null) {
  const q = question.toLowerCase().replaceAll("ё", "е");
  const bits: string[] = [];
  if (/привет|здравств|добрый/.test(q)) {
    bits.push(
      "Здравствуйте. Я OPS. Помогу с объявлениями, тарифами и работой AvitoOps. Просто напишите или скажите, что нужно.",
    );
  }
  if (/тариф|цен|стоим|сколько|подписк|старт|рост|бизнес|сеть/.test(q)) {
    bits.push(`${guestPriceLine()} ${tariffLine}. Подробности на странице тарифов. Рекламный бюджет платится отдельно, с депозита.`);
  }
  if (/регистр|начать|подключ|аккаунт|войти|логин/.test(q)) {
    bits.push(
      "Зарегистрироваться можно сразу. Первые сутки бесплатно: одно объявление и все функции — текст, кадр, продвижение с депозита и ответы покупателям. Со вторых суток работает оплаченный тариф. Войти в уже созданный аккаунт можно со страницы входа.",
    );
  }
  if (/парол|смс|код/.test(q)) {
    bits.push("Пароль Авито и коды из SMS мы не просим и не храним. Пароль на сайте задаёте сами при регистрации.");
  }
  if (/вместо меня|заполнить агент|агент заполн/.test(q)) {
    bits.push(
      "На тарифах Рост, Бизнес и Сеть в анкете есть кнопка «Заполнить агенту вместо меня». Куратор задаёт вопросы и вписывает ответы в поля. Галочку согласия ставите сами. На Старте анкету заполняют вручную.",
    );
  } else if (/ручн|объявлен|онбординг|форм|ввести|заполн|анкет/.test(q)) {
    bits.push("Карточка собирается в разговоре. Форма остаётся, если удобнее руками. На Старте копирайтер записывает ваши слова.");
  }
  if (/кто вы|кто ты|вы кто|ты кто|представьтесь|представься/.test(q)) {
    bits.push(
      "Я OPS, AI-авитолог AvitoOps. Помогу с объявлениями, тарифами и работой сервиса. Напишите или скажите, что нужно.",
    );
  }
  if (/лид|чат|ответ/.test(q) && !/кто вы|кто ты|вы кто|ты кто|представь/.test(q)) {
    bits.push(
      "Ответы покупателям идут по правилам из разговора, без нового «да» на каждое сообщение. Случай из списка «написать вам» приходит в этот же диалог, на Авито ответа нет.",
    );
  }
  if (/пауз|останов/.test(q)) {
    bits.push("После вашего «да» пауза останавливает тексты, фото, продвижение и ответы. Без «да» никто не останавливается.");
  }
  if (/депозит|реклам/.test(q)) {
    bits.push("Реклама Авито не входит в подписку. Сумму кладёте на депозит кнопкой в биллинге. Куратор платёж сам не проводит.");
  }
  if (/оплат|счет|счёт|юкасс|юkassa/.test(q)) {
    bits.push("Тариф и депозит оплачиваются кнопкой в биллинге. Карту в чат не присылайте. Куратор оплату сам не проводит.");
  }
  if (/прокси|канал/.test(q)) {
    bits.push("Подключение к Авито делаем мы. Отдельные настройки вам не нужны.");
  }
  if (/отчет|отчёт|гарант|топ|продаж/.test(q)) {
    bits.push("Топ в поиске, число заявок, обход правил и мгновенные продажи не обещаем. Еженедельный отчёт в работу пока не входит.");
  }
  if (/куки|cookie/.test(q)) {
    bits.push("Cookie нужны, чтобы после входа вы оставались в кабинете. Рекламных cookie нет. Согласие показывается внизу страницы.");
  }
  if (/оферт|договор|юрист/.test(q)) {
    bits.push("Оферта лежит на странице оферты. Контакты и реквизиты — на странице контактов.");
  }
  if (cabinet && /мой|мои|статус|сколько у|кабинет/.test(q)) bits.push(cabinet);
  if (bits.length === 0) {
    bits.push(
      "Могу ответить про тарифы, регистрацию, оплату, депозит и карточку объявления. Напишите вопрос своими словами. Чтобы сохранить разговор, нужна регистрация.",
    );
  }
  return bits.join(" ");
}

async function grokReply(message: string, history: CuratorTurn[], cabinet: string | null) {
  const prior = history
    .slice(-6)
    .map((turn) => `${turn.role === "user" ? "Клиент" : "Куратор"}: ${turn.content}`)
    .join("\n");
  return askGrok(curatorSystemPrompt(cabinet), prior ? `${prior}\nКлиент: ${message}` : message);
}

export async function replyAsCurator(
  message: string,
  history: CuratorTurn[],
  cabinet: string | null,
  useModel: boolean,
) {
  if (useModel && seniorConfigured()) {
    try {
      const text = await grokReply(message, history, cabinet);
      if (text) return speak(text);
    } catch {
      return speak(localReply(message, cabinet));
    }
  }
  return speak(localReply(message, cabinet));
}

export function cabinetBrief(input: {
  plan: string | null;
  subscriptionStatus: string | null;
  access: string;
  listingCount: number;
  publishStarted: number;
  publishQuota: number;
  publishQueued: number;
  depositRub: number;
  hasProfile: boolean;
}) {
  const daily =
    input.plan && isPlan(input.plan)
      ? `За сутки на тарифе: ${DAILY_QUOTA[input.plan].publish} объявлений, ${DAILY_QUOTA[input.plan].update} правок, продвижение до ${DAILY_QUOTA[input.plan].promo} объявлений. Ответы покупателям по правилам клиента.`
      : "Тариф ещё не выбран.";
  return [
    `Тариф: ${planTitle(input.plan)}.`,
    daily,
    `Выкладка сегодня: ${input.publishStarted} из ${input.publishQuota}, в очереди ${input.publishQueued}.`,
    `Подписка: ${input.subscriptionStatus ? subscriptionStatusLabel(input.subscriptionStatus) : "нет оплаты"}.`,
    `Доступ: ${accessLabel(input.access)}.`,
    `Карточек в кабинете: ${input.listingCount}. Число карточек тарифом не ограничено.`,
    `Депозит: ${formatRub(input.depositRub)}.`,
    input.hasProfile ? "Анкета заполнена." : "Анкету можно заполнить формой, если так удобнее.",
  ].join(" ");
}
